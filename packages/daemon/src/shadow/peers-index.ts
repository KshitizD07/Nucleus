import fs from "node:fs";
import path from "node:path";
import { WorkspaceJail } from "../jail/jail.js";

export interface PeerRecord {
  nodeId: string;
  lane: string;
  status: "idle" | "active" | "review";
  activeFile: string | null;
}

export class PeersIndexManager {
  private readonly jail: WorkspaceJail;
  private readonly nucleusDir: string;
  private readonly peersFilePath: string;
  private peers: Map<string, PeerRecord> = new Map();

  constructor(workspaceRoot: string) {
    this.jail = new WorkspaceJail(workspaceRoot);
    this.nucleusDir = this.jail.resolveSafe(".nucleus");
    this.peersFilePath = this.jail.resolveSafe(path.join(".nucleus", "PEERS.md"));
    fs.mkdirSync(this.nucleusDir, { recursive: true });
    this.render(); // Ensure .nucleus/PEERS.md is immediately created upon initialization
  }

  public setPeer(peer: PeerRecord): void {
    this.peers.set(peer.nodeId, peer);
    this.render();
  }

  public removePeer(nodeId: string): void {
    if (this.peers.delete(nodeId)) {
      this.render();
    }
  }

  public updatePeerFocus(nodeId: string, activeFile: string | null, status?: "idle" | "active" | "review"): void {
    const peer = this.peers.get(nodeId);
    if (!peer) return;
    peer.activeFile = activeFile;
    if (status) peer.status = status;
    this.render();
  }

  public getPeers(): PeerRecord[] {
    return Array.from(this.peers.values());
  }

  public render(): void {
    const lines: string[] = [
      "# Active Room Peers & Live Shadow Directory",
      "",
      "> This file is automatically generated and updated in real time by your local `sphere-node` daemon.",
      "> It informs you and your AI coding agent (Claude Code, Antigravity, Aider) what peer lanes are active,",
      "> what files they are editing, and where their live uncommitted code can be inspected.",
      "",
      "## Active Peers in Room",
      "",
      "| Lane | Node ID | Status | Active File / Focus | Live Shadow Mirror Path |",
      "| :--- | :--- | :--- | :--- | :--- |"
    ];

    if (this.peers.size === 0) {
      lines.push("| *(none)* | *(none)* | idle | *(no other peers connected)* | `.nucleus/shadows/` |");
    } else {
      for (const peer of this.peers.values()) {
        const activeFileDisplay = peer.activeFile ? `\`${peer.activeFile}\`` : "*(idle)*";
        lines.push(
          `| \`${peer.lane}\` | \`${peer.nodeId}\` | ${peer.status} | ${activeFileDisplay} | \`.nucleus/shadows/${peer.lane}/\` |`
        );
      }
    }

    lines.push(
      "",
      "---",
      "",
      "## Instructions for AI Coding Agents",
      "",
      "### 1. Task Specifications & Requirements",
      "When claiming or working on an assigned task from `.nucleus/tasks.json`:",
      "- **Inspect `spec_file`**: If the task has a `spec_file` (e.g. `CONTRACT/specs/<feature>.md`), read that file immediately from disk. It contains complete feature requirements, request/response schemas, error handling expectations, and acceptance criteria.",
      "- **Inspect `spec_url`**: If the task points to a `spec_url` (e.g. Figma node, Linear issue, PRD), fetch or inspect the external specification before writing code.",
      "- **Read `description`**: If a description is provided in `.nucleus/tasks.json`, treat it as authoritative task scope.",
      "",
      "### 2. Cross-Lane Counterpart Alignment",
      "When building features that interact with other lanes:",
      "1. **Do not guess API shapes, payload structures, or database schemas.**",
      "2. Check the table above. If a peer lane has counterpart code in progress, read their live uncommitted file directly from `.nucleus/shadows/<lane>/`.",
      "3. *Example:* If building a frontend screen, inspect `.nucleus/shadows/backend/<api-path>` to see the exact request body fields and response envelope.",
      "4. Living shared contracts are in `CONTRACT/api.md` (replicated live across all room contributors).",
      "5. The files in `.nucleus/shadows/` are synchronized live by the room daemon without needing Git commits or pushes.",
      ""
    );

    // Dynamic template customization: incorporate project-specific guidelines if present
    const contractTemplatePath = this.jail.resolveSafe(path.join("CONTRACT", "peers.template.md"));
    const nucleusTemplatePath = this.jail.resolveSafe(path.join(".nucleus", "peers.template.md"));
    let customTemplate: string | null = null;

    if (fs.existsSync(contractTemplatePath)) {
      customTemplate = fs.readFileSync(contractTemplatePath, "utf8");
    } else if (fs.existsSync(nucleusTemplatePath)) {
      customTemplate = fs.readFileSync(nucleusTemplatePath, "utf8");
    }

    if (customTemplate && customTemplate.trim()) {
      lines.push(
        "---",
        "",
        "## Project-Specific Collaboration Rules",
        "",
        customTemplate.trim(),
        ""
      );
    }

    fs.writeFileSync(this.peersFilePath, lines.join("\n"), "utf8");
  }

  public getPeersFilePath(): string {
    return this.peersFilePath;
  }
}
